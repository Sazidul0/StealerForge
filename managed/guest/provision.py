def step(name, critical=True):
    def wrap(function):
        @functools.wraps(function)
        def run(*args):
            started = time.time()
            try:
                detail = function(*args)
                RESULTS[name] = {'ok': True, 'critical': critical, 'detail': detail,
                                 'seconds': round(time.time() - started, 1)}
            except Exception as exc:
                RESULTS[name] = {'ok': False, 'critical': critical, 'error': f'{type(exc).__name__}: {exc}',
                                 'trace': traceback.format_exc()[-2000:]}
            save()
        return run
    return wrap


def save():
    STATE.mkdir(exist_ok=True)
    failed = [k for k, v in RESULTS.items() if not v['ok'] and v['critical']]
    (STATE / 'provision.json').write_text(json.dumps({'ok': not failed, 'failed': failed, 'steps': RESULTS},
                                                      indent=2), encoding='utf-8')


def run(args, timeout=600, check=True):
    result = subprocess.run(args, capture_output=True, text=True, timeout=timeout, creationflags=NO_WINDOW)
    if check and result.returncode:
        raise RuntimeError(f'{args[0]} exited {result.returncode}: {(result.stdout + result.stderr)[-800:]}')
    return result.stdout


def ps(script, timeout=600, check=True):
    return run(['powershell.exe', '-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass', '-Command', script],
               timeout, check)


def reg_set(root, path, name, value, kind=None):
    kind = kind if kind is not None else (winreg.REG_DWORD if isinstance(value, int) else winreg.REG_SZ)
    with winreg.CreateKeyEx(root, path, 0, winreg.KEY_WRITE | winreg.KEY_WOW64_64KEY) as key:
        winreg.SetValueEx(key, name, 0, kind, value)


