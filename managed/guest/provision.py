class SECItem(ctypes.Structure):
    _fields_ = [('type', ctypes.c_uint), ('data', ctypes.POINTER(ctypes.c_ubyte)), ('len', ctypes.c_uint)]


def nss_decrypt(profile, blob):
    """Decrypt one logins.json field with Firefox's own NSS, exactly as a stealer would."""
    os.add_dll_directory(str(FIREFOX_DIR))
    nss = ctypes.CDLL(str(FIREFOX_DIR / 'nss3.dll'))
    nss.NSS_Init.argtypes = [ctypes.c_char_p]
    nss.PK11SDR_Decrypt.argtypes = [ctypes.POINTER(SECItem), ctypes.POINTER(SECItem), ctypes.c_void_p]
    nss.SECITEM_ZfreeItem.argtypes = [ctypes.POINTER(SECItem), ctypes.c_int]
    if nss.NSS_Init(b'sql:' + str(profile).encode('mbcs')) != 0:
        raise RuntimeError('NSS_Init failed')
    try:
        buffer = ctypes.create_string_buffer(blob, len(blob))
        source, output = SECItem(0, ctypes.cast(buffer, ctypes.POINTER(ctypes.c_ubyte)), len(blob)), SECItem()
        if nss.PK11SDR_Decrypt(ctypes.byref(source), ctypes.byref(output), None) != 0:
            raise RuntimeError('PK11SDR_Decrypt failed')
        value = ctypes.string_at(output.data, output.len)
        nss.SECITEM_ZfreeItem(ctypes.byref(output), 0)
        return value.decode()
    finally:
        nss.NSS_Shutdown()


class Marionette:
    """Minimal client for Firefox's remote protocol: lets Firefox itself store (and encrypt) the canary logins."""
    def __init__(self, port=2828, timeout=90):
        deadline = time.time() + timeout
        while True:
            try:
                self.sock = socket.create_connection(('127.0.0.1', port), timeout=30)
                break
            except OSError:
                if time.time() > deadline:
                    raise RuntimeError('Firefox Marionette did not start')
                time.sleep(1)
        self.counter = 0
        self.read()

    def read(self):
        size = b''
        while not size.endswith(b':'):
            byte = self.sock.recv(1)
            if not byte:
                raise RuntimeError('Marionette connection closed')
            size += byte
        data = b''
        while len(data) < int(size[:-1]):
            data += self.sock.recv(int(size[:-1]) - len(data))
        return json.loads(data)

    def call(self, name, params=None):
        self.counter += 1
        payload = json.dumps([0, self.counter, name, params or {}]).encode()
        self.sock.sendall(str(len(payload)).encode() + b':' + payload)
        while True:
            message = self.read()
            if isinstance(message, list) and message[:2] == [1, self.counter]:
                if message[2]:
                    raise RuntimeError(f'{name}: {message[2]}')
                return message[3]


