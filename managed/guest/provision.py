class Blob(ctypes.Structure):
    _fields_ = [('cbData', wt.DWORD), ('pbData', ctypes.POINTER(ctypes.c_char))]


def _dpapi(function, data):
    source = Blob(len(data), ctypes.cast(ctypes.create_string_buffer(data, len(data)), ctypes.POINTER(ctypes.c_char)))
    output = Blob()
    if not function(ctypes.byref(source), None, None, None, None, 0, ctypes.byref(output)):
        raise ctypes.WinError()
    try:
        return ctypes.string_at(output.pbData, output.cbData)
    finally:
        ctypes.windll.kernel32.LocalFree(output.pbData)


def dpapi_protect(data):
    return _dpapi(ctypes.windll.crypt32.CryptProtectData, data)


def dpapi_unprotect(data):
    return _dpapi(ctypes.windll.crypt32.CryptUnprotectData, data)


def chromium_key(user_data):
    state = json.loads((user_data / 'Local State').read_text(encoding='utf-8'))
    encrypted = base64.b64decode(state['os_crypt']['encrypted_key'])
    if not encrypted.startswith(b'DPAPI'):
        raise RuntimeError('Unexpected os_crypt key format')
    return dpapi_unprotect(encrypted[5:])


def v10(key, plaintext):
    from Crypto.Cipher import AES
    nonce = os.urandom(12)
    cipher = AES.new(key, AES.MODE_GCM, nonce=nonce)
    ciphertext, tag = cipher.encrypt_and_digest(plaintext)
    return b'v10' + nonce + ciphertext + tag


def v10_decrypt(key, blob):
    from Crypto.Cipher import AES
    cipher = AES.new(key, AES.MODE_GCM, nonce=blob[3:15])
    return cipher.decrypt_and_verify(blob[15:-16], blob[-16:])


def chrome_time(days_ago=0):
    # Microseconds since 1601-01-01 (Windows FILETIME epoch, as used by Chromium).
    return int((time.time() - days_ago * 86400 + 11644473600) * 1_000_000)


def insert(db, table, values):
    """Insert by column name; NOT NULL columns without defaults that we do not set get neutral values."""
    columns = db.execute(f'PRAGMA table_info({table})').fetchall()
    row = dict(values)
    for _, name, kind, notnull, default, _ in columns:
        if name in row or not notnull or default is not None:
            continue
        row[name] = b'' if 'BLOB' in (kind or '').upper() else '' if 'TEXT' in (kind or '').upper() or 'CHAR' in (kind or '').upper() else 0
    known = {c[1] for c in columns}
    row = {k: v for k, v in row.items() if k in known}
    db.execute(f'INSERT INTO {table} ({",".join(row)}) VALUES ({",".join("?" * len(row))})', list(row.values()))


def write(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    (path.write_bytes if isinstance(data, bytes) else lambda d: path.write_text(d, encoding='utf-8'))(data)


def leveldb(folder, records):
    """A small LevelDB-shaped folder; stealers copy these folders wholesale or regex-scan the files."""
    write(folder / 'CURRENT', 'MANIFEST-000001\n')
    write(folder / 'LOCK', b'')
    write(folder / 'LOG', f'{time.strftime("%Y/%m/%d-%H:%M:%S")}.000000 1 Recovering log #3\n')
    write(folder / 'MANIFEST-000001', b'V\xea\x8d\x8f\x1a\x00\x01\x01\x1aleveldb.BytewiseComparator')
    body = b''.join(b'\x01' + k.encode() + b'\x00' + v.encode() for k, v in records)
    write(folder / '000003.log', b'\x00' * 7 + body)
    write(folder / '000005.ldb', body)


