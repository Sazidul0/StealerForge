def signed_by(path, signer):
    out = ps(f'$s = Get-AuthenticodeSignature -LiteralPath {json.dumps(str(path))}; '
             '"$($s.Status)|$($s.SignerCertificate.Subject)"').strip()
    status, _, subject = out.partition('|')
    if status != 'Valid' or f'O={signer}' not in subject and f'CN={signer}' not in subject:
        raise RuntimeError(f'Signature check failed for {path.name}: {out}')
    return subject


